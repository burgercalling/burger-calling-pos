"use client";

import { useCurrentUser } from "@/hooks/use-auth";

export function PrintReportHeader({
  reportName,
  subtitle,
  filtersSummary,
}: {
  reportName: string;
  subtitle?: string;
  filtersSummary?: string;
}) {
  const { data: user } = useCurrentUser();
  const generatedAt = new Date().toLocaleString("en-IN", {
    dateStyle: "medium",
    timeStyle: "short",
  });

  return (
    <div className="print-only mb-5 border-b-2 border-stone-900 pb-4">
      <div className="flex items-start justify-between gap-4">
        <div className="flex items-center gap-3">
          <div className="flex h-12 w-12 items-center justify-center rounded-xl bg-orange-600 text-lg font-black text-white">
            BC
          </div>
          <div>
            <h1 className="text-xl font-extrabold tracking-tight text-stone-900">
              BURGER CALLING
            </h1>
            <p className="text-xs font-medium text-stone-600">
              100% Pure Vegetarian QSR · Official Business Report
            </p>
            {user?.franchise && (
              <p className="mt-0.5 text-xs text-stone-700">
                Outlet: <strong>{user.franchise.name}</strong> ({user.franchise.outlet_code})
              </p>
            )}
          </div>
        </div>

        <div className="text-right text-xs text-stone-700">
          <p className="text-sm font-bold uppercase tracking-wide text-orange-700">
            {reportName}
          </p>
          {subtitle && <p className="text-stone-600">{subtitle}</p>}
          <p className="mt-1">
            Generated: <strong>{generatedAt}</strong>
          </p>
          <p>
            Printed By: <strong>{user?.full_name ?? "Admin"}</strong>
          </p>
        </div>
      </div>

      {filtersSummary && (
        <div className="mt-3 rounded-md border border-stone-200 bg-stone-50 px-3 py-1.5 text-xs text-stone-700">
          <strong>Applied Filters:</strong> {filtersSummary}
        </div>
      )}
    </div>
  );
}

export function PrintReportFooter() {
  return (
    <div className="print-only mt-6 border-t border-stone-300 pt-2.5 text-center text-[10px] text-stone-500">
      <div className="flex items-center justify-between">
        <span>Generated by Burger Calling POS v1.1</span>
        <span>100% Pure Veg QSR Network · Confidential</span>
      </div>
    </div>
  );
}
